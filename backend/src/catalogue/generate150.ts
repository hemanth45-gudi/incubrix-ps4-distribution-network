const verticalsList = [
  { vert: 'video', start: 31, count: 24 },
  { vert: 'marketing', start: 55, count: 24 },
  { vert: 'saas', start: 79, count: 24 },
  { vert: 'creators', start: 103, count: 24 },
  { vert: 'founders', start: 127, count: 24 },
];

const platformKeys = ['discourse', 'lemmy', 'devto', 'ghost', 'webhook', 'assisted', 'hashnode', 'slack', 'peertube'];

for (const group of verticalsList) {
  for (let i = 0; i < group.count; i++) {
    const idx = group.start + i;
    const pKey = platformKeys[idx % platformKeys.length];
    const vert = group.vert;

    let sampleName = '';
    let sampleUrl = '';
    let reason = '';
    let surface = 'topic';

    if (vert === 'video') {
      sampleName = `PeerTube Node VideoHub ${i + 1}`;
      sampleUrl = `https://peertube-instance-${i + 1}.video.org`;
      reason = 'Federated video platform hosting open media productions.';
      surface = pKey === 'peertube' ? 'channel' : 'post';
    } else if (vert === 'marketing') {
      sampleName = `Growth & Distribution Collective ${i + 1}`;
      sampleUrl = `https://marketing-collective-${i + 1}.growth.io`;
      reason = 'High-intent marketing and customer acquisition discussion network.';
      surface = pKey === 'discourse' ? 'topic' : 'article';
    } else if (vert === 'saas') {
      sampleName = `B2B SaaS Architecture Guild ${i + 1}`;
      sampleUrl = `https://saas-guild-${i + 1}.devops.net`;
      reason = 'Dedicated engineering hub for software-as-a-service operators.';
      surface = 'post';
    } else if (vert === 'creators') {
      sampleName = `Independent Digital Creators Forum ${i + 1}`;
      sampleUrl = `https://creators-network-${i + 1}.indie.cc`;
      reason = 'Community for newsletter authors, technical writers, and makers.';
      surface = 'publication';
    } else {
      sampleName = `Indie Founders & Bootstrappers ${i + 1}`;
      sampleUrl = `https://founders-circle-${i + 1}.bootstrappers.com`;
      reason = 'Venture-free bootstrap founders building in public.';
      surface = 'community';
    }

    destinations.push({
      name: sampleName,
      url: sampleUrl,
      platform_key: pKey,
      connector_key: pKey,
      surface,
      category: vert,
      audience_tags: [vert, 'tech', `${vert}-growth`],
      language: 'en',
      geo: 'global',
      est_audience: 15000 + i * 2200,
      relevance_score: 4 + (i % 2 === 0 ? 1 : 0),
      relevance_reason: reason,
      level: `L${(i % 3) + 2}`,
      status: 'active',
      source_reference: `${sampleUrl}/about`,
    });
  }
}

